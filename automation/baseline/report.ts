import type { Measurement, RunBundle } from '@/automation/records/schema';
import { authorClasses } from '@/automation/records/schema';

// Renders the concise Markdown report for a set of run bundles. Every rate
// states its denominator, and unknown measurements are counted as unknown,
// never dropped from the total or read as zero.

export interface ReportMeta {
  repo: string;
  collectedAt: string;
  sourceCommit: string;
  since: string;
  windowDays: number;
}

export interface UsageSummary {
  known: number;
  unknown: number;
  reasons: string[];
}

export function summarizeMeasurements(values: Measurement[]): UsageSummary {
  const reasons = new Set<string>();
  let known = 0;
  for (const value of values) {
    if (value.status === 'known') known += 1;
    else reasons.add(value.reason);
  }
  return { known, unknown: values.length - known, reasons: [...reasons] };
}

function median(values: number[]): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

function hours(seconds: number | null): string {
  return seconds === null ? 'n/a' : `${(seconds / 3600).toFixed(1)} h`;
}

function usageLine(label: string, summary: UsageSummary, total: number): string {
  const reasons = summary.reasons.length ? ` (${summary.reasons.join('; ')})` : '';
  return `| ${label} | ${summary.known} of ${total} | ${summary.unknown} of ${total}${reasons} |`;
}

export function renderReport(bundles: RunBundle[], meta: ReportMeta): string {
  const total = bundles.length;
  const by = <K extends string>(key: (b: RunBundle) => K) => {
    const out = new Map<K, number>();
    for (const b of bundles) out.set(key(b), (out.get(key(b)) ?? 0) + 1);
    return out;
  };
  const outcomes = by((b) => b.outcome.outcome);
  const classes = by((b) => b.run.author.class);
  const merged = bundles.filter((b) => b.outcome.outcome === 'merged');
  const observing = merged.filter((b) => b.outcome.observation.status === 'observing').length;
  const complete = merged.length - observing;
  const reverted = merged.filter((b) => b.outcome.reverts.length > 0);
  const withFollowUps = merged.filter((b) => b.outcome.followUps.length > 0);

  const withChecks = bundles.filter((b) => b.run.verification.allChecksSucceeded !== null);
  const green = withChecks.filter((b) => b.run.verification.allChecksSucceeded).length;
  const attempts = bundles.map((b) => b.run.attempts.ciRunAttemptsOnHead);
  const knownAttempts = attempts.filter((a) => a.status === 'known');
  const rerun = knownAttempts.filter((a) => a.status === 'known' && a.value > 1).length;
  const fixups = merged.filter(
    (b) => b.run.attempts.headCommits.status === 'known' && b.run.attempts.headCommits.value > 1,
  ).length;
  const recordedReviews = merged.filter((b) => b.reviews.length > 0).length;

  const openTimes = merged
    .map((b) => b.run.prOpenDuration)
    .flatMap((m) => (m.status === 'known' ? [m.value] : []));

  const usage = (pick: (b: RunBundle) => Measurement) => summarizeMeasurements(bundles.map(pick));

  const lines = [
    `# Maintainer baseline: ${meta.repo}`,
    '',
    `Schema version 1. Collected ${meta.collectedAt} from commit \`${meta.sourceCommit}\`.`,
    `Range: PRs created or closed since ${meta.since}. Observation window: ${meta.windowDays} days after merge.`,
    'Source: public GitHub metadata and git history only. Generated by `automation/baseline/collect.ts`.',
    '',
    '## Runs',
    '',
    `${total} runs (one per PR head).`,
    '',
    '| Outcome | Runs |',
    '| --- | --- |',
    ...(['merged', 'closed-unmerged', 'open'] as const).map(
      (o) => `| ${o} | ${outcomes.get(o) ?? 0} |`,
    ),
    '',
    '| Author class | Runs |',
    '| --- | --- |',
    ...authorClasses.map((c) => `| ${c} | ${classes.get(c) ?? 0} |`),
    '',
    '## Outcomes after merge',
    '',
    `- Observation window complete for ${complete} of ${merged.length} merged runs; ${observing} still observing (their regression counts are not final).`,
    `- Reverted within the window: ${reverted.length} of ${merged.length}${reverted.length ? ` (${reverted.map((b) => `#${b.run.prNumber}`).join(', ')})` : ''}.`,
    `- With a follow-up issue or fix PR referencing them within the window: ${withFollowUps.length} of ${merged.length}. Heuristic: an issue, or a PR titled \`fix...\`, that cites the PR number.`,
    '',
    '## Verification and attempts',
    '',
    `- All CI checks succeeded on the final head: ${green} of ${withChecks.length} runs with checks (${total - withChecks.length} runs had no check recorded on the head).`,
    `- CI rerun on the final head (run attempt above 1): ${rerun} of ${knownAttempts.length} runs with a recorded CI run (${total - knownAttempts.length} unknown).`,
    `- Merged with more than one commit on the branch (fixups): ${fixups} of ${merged.length}.`,
    `- Merged runs with a review recorded on GitHub (review or posted verdict): ${recordedReviews} of ${merged.length}. Local subagent reviews left no per-SHA record and are unknown.`,
    `- Median time from PR creation to merge: ${hours(median(openTimes))} over ${openTimes.length} merged runs.`,
    '',
    '## Usage and cost',
    '',
    '| Measurement | Known | Unknown |',
    '| --- | --- | --- |',
    usageLine(
      'Input tokens',
      usage((b) => b.run.usage.inputTokens),
      total,
    ),
    usageLine(
      'Output tokens',
      usage((b) => b.run.usage.outputTokens),
      total,
    ),
    usageLine(
      'Cost (USD)',
      usage((b) => b.run.usage.costUsd),
      total,
    ),
    usageLine(
      'Agent duration',
      usage((b) => b.run.usage.agentDuration),
      total,
    ),
    usageLine(
      'Human interventions',
      usage((b) => b.run.humanInterventions),
      total,
    ),
    usageLine(
      'Agent attempts',
      usage((b) => b.run.attempts.agentAttempts),
      total,
    ),
    '',
    'No cost per successful task is reported: the cost of every run is unknown.',
    '',
    '## Limits',
    '',
    '- One run per PR: work that never reached a PR (abandoned before opening) is invisible here.',
    '- CI evidence covers the final head SHA only; checks on earlier heads of the same PR are not counted.',
    '- Branch commit counts include merges of `main` into the branch, so "fixups" overstates review-driven rework.',
    '- `loop` means the maintainer account plus a Claude Co-Authored-By trailer. It shows Claude wrote the commits, not that the run was unattended; human prompting is not recorded.',
    '- Follow-up and revert links are reference heuristics within the window, not a causal analysis.',
    '- Vetted status uses the grant date in `docs/loops/10-external-contributions.md`.',
    '',
  ];
  return lines.join('\n');
}
